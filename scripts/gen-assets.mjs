// Embeds fonts and the resvg wasm as base64 so each API bundle is fully self contained.
import { readFileSync, writeFileSync } from 'node:fs';
const b64 = (p) => readFileSync(p).toString('base64');
const out = `// GENERATED by scripts/gen-assets.mjs, do not edit
export const displayB64 = '${b64('node_modules/@fontsource/bricolage-grotesque/files/bricolage-grotesque-latin-800-normal.woff')}';
export const monoB64 = '${b64('node_modules/@fontsource/jetbrains-mono/files/jetbrains-mono-latin-700-normal.woff')}';
export const wasmB64 = '${b64('node_modules/@resvg/resvg-wasm/index_bg.wasm')}';
`;
writeFileSync('server/lib/assets.generated.ts', out);
console.log('assets generated', (out.length / 1e6).toFixed(1) + 'MB');
